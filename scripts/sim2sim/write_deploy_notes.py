"""Write `DEPLOYMENT.md` for an exported S7 model: what a deployment of the policy needs to know,
from the model folder's `deployment_info.yaml` / `pick_place_profile.yaml` (training side) and the
PAL sim2sim runs' logs (deployer side).

  python3 write_deploy_notes.py --model <model dir> --runs <runs dir> --out DEPLOYMENT.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import yaml

ARM = [f"arm_left_{i}_joint" for i in range(1, 8)]


def table(header: list[str], rows: list[list]) -> str:
  out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
  out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
  return "\n".join(out)


def f(v, n=4):
  return f"{v:.{n}f}"


def hold_rows(run: Path, model: Path) -> list[list]:
  d = np.genfromtxt(run / "hold_probe.csv", delimiter=",", names=True)
  t = d["t"] - d["t"][0]
  start = json.loads((model / "deployment_start_config.json").read_text())["joint_positions"]
  m = t > t[-1] - 3.0
  rows = []
  for j, n in enumerate(ARM):
    q, qd, tau = d[f"q{j}"][m], d[f"qd{j}"][m], d[f"tau{j}"][m]
    flips = float(np.mean(np.diff(np.sign(tau)) != 0))
    rows.append(
      [n, f(q.mean() - start[n]), f(np.sqrt((qd**2).mean()), 2), f(np.ptp(tau), 1), f(tau.mean(), 1), f(flips, 2)]
    )
  return rows


def main() -> None:
  p = argparse.ArgumentParser()
  p.add_argument("--model", type=Path, required=True)
  p.add_argument("--runs", type=Path, required=True)
  p.add_argument("--out", type=Path, required=True)
  args = p.parse_args()
  info = yaml.safe_load((args.model / "deployment_info.yaml").read_text())
  prof = yaml.safe_load((args.model / "pick_place_profile.yaml").read_text())
  start = json.loads((args.model / "deployment_start_config.json").read_text())["joint_positions"]
  ref = np.load(args.model / "mujoco_reference.npz")
  pol, plant, act, obs, scene = info["policy"], info["plant"], info["action"], info["observation"], info["scene"]
  T = json.loads((args.runs / "T2_rctp_s3" / "summary.json").read_text())
  TC = json.loads((args.runs / "TC2_rctp_s3" / "summary.json").read_text())

  L: list[str] = []
  a = L.append
  a("# RCTP seed 3 — what a deployment needs to know\n")
  a(
    "Written from `deployment_info.yaml` / `pick_place_profile.yaml` (this folder, generated by "
    "`scripts/sim2sim/export_for_pal_s7.py` from the training configuration) and the PAL-simulator runs "
    "of 2026-09-30 on Geoffery. Frames: `base_link` (PAL's), metres, radians, N·m, seconds.\n"
  )

  a("## 1. The policy\n")
  a(
    table(
      ["", ""],
      [
        ["checkpoint", f"`{pol['checkpoint']}` sha256 `{pol['checkpoint_sha256'][:16]}…` (S7-5 control RCTP seed 3, IAS job 160236, 5000 iterations, wandb `n0nglkrt`)"],
        ["ONNX", f"`{pol['onnx']}` sha256 `{pol['onnx_sha256'][:16]}…`, 38 → 8, max abs difference to the PyTorch actor 7.6e-6 over 73 observations"],
        ["task", f"`{pol['task']}`, selectors {json.dumps(pol['selectors'])}"],
        ["trained on", "`-s75` @ `83e9929` (branch `siwei-s7-5`); exported with pal_mjlab `" + pol["code"]["pal_mjlab_commit"][:7] + "` (" + pol["code"]["pal_mjlab_branch"] + ")"],
        ["control rate", f"{info['timing']['policy_rate_hz']:.0f} Hz (physics {info['timing']['physics_dt_s'] * 1000:.0f} ms × {info['timing']['decimation']}); 10 s episodes"],
        ["joint convention", "identical to PAL's URDF: **`joint_signs` all +1**, observations in `base_link` (pal_mjlab `5e09c30` ported `fda9492` before S7-2). S5.2 / S7-1 policies need the sign flips and the 0.9 m offset; this one does not."],
      ],
    )
  )
  a("")

  a("## 2. Initial position\n")
  a("The training reset pose (`default_joint_pos`, zero velocity; `deployment_start_config.json` holds all 30 joints). The policy's actions are `default + scale · a`, so this is also the action origin.\n")
  rows = []
  for n in ARM + ["gripper_left_finger_joint"]:
    rows.append([n, f(start[n], 4), f(act["scale"][n], 3), f(act["slew_rate_rad_per_step"][n], 4)])
  a(table(["joint (policy order)", "default q [rad]", "action scale [rad]", "slew [rad / 20 ms]"], rows))
  a("")
  other = {k: v for k, v in start.items() if k not in ARM and k != "gripper_left_finger_joint"}
  a("Every other joint, at its training default (the right arm is parked, pelvis and legs hold the stance; on PAL these are the simulator's / the robot's own controllers' job):\n")
  a(table(["joint", "q [rad or m]"], [[k, f(v, 4)] for k, v in other.items()]))
  a("")
  tcp0 = ref["tcp_b"][0, 0]
  q0 = ref["tcp_quat_b"][0, 0]
  a(
    f"TCP at the start (site `tcp_left` = `arm_left_7_link` + (0, 0, 0.148), no rotation offset), MuJoCo: "
    f"position ({tcp0[0]:.3f}, {tcp0[1]:.3f}, {tcp0[2]:.3f}), quaternion wxyz ({q0[0]:.3f}, {q0[1]:.3f}, {q0[2]:.3f}, {q0[3]:.3f}). "
    "On PAL under G20 without gravity feed-forward the arm rests 0.02 rad lower at the elbow: TCP (0.425, 0.154, 0.032), max start error 0.021 rad. "
    "PAL's standing base_link was at (0.0204, 0.0010, 0.9045) in the simulator's world; the training base_link is fixed at (0, 0, 0.9).\n"
  )

  a("## 3. Joint gains and limits\n")
  a("Trained plant (`GAINS=G20`, gravity compensation off everywhere = `impedance_control_v37` for arm 1–4). Torque law in training and in PAL's `DirectImpedanceControl`: τ = K (q_des − q) + D (0 − q̇) + 0.\n")
  rows = []
  for n, v in plant["actuators"].items():
    fr = v["force_range_Nm"]
    lo = v["joint_actfrc_range_Nm"]
    rng = v["joint_range"]
    rows.append(
      [
        n,
        f(v["kp"], 3),
        f(v["kd"], 3),
        f"±{fr[1]:g}" if fr else "-",
        f"±{lo[1]:g}" if lo else "-",
        f(v["armature"], 5),
        f"[{rng[0]:.3f}, {rng[1]:.3f}]" if rng else "-",
      ]
    )
  a(table(["joint", "K [N·m/rad]", "D [N·m·s/rad]", "effort limit", "T cap (0.7 ×)", "armature", "range [rad]"], rows))
  a("")
  a(
    "K and D of the seven left-arm joints are what `spawn_grasp_controller.py` reads from `params/env.yaml` "
    "(the real training dump, from IAS) and sets as `stiffness_factor` / `damping_factor`. "
    "PAL's own arm PID configuration for reference (`kangaroo-pal-physics-simulator/config/pids`): arm 1–4 p 500 / d 10, arm 5–7 p 100 / d 1, torque clamps 40 / 40 / 20 / 20 / 20 / 20 / 20; "
    "`impedance_control_v37` has `stiffness_factor` 998.79 / 523.54 and `damping_factor` 63.585 / 33.329 for arm 1–4 (with `feedforward_prev_cmd: true`, `integral_factor: 0`) and no files for arm 5–7.\n"
  )

  a("### G20 does not run on PAL's simulator at the wrists\n")
  a("Hold test (`hold_probe.sh`: the start pose under the trained K / D, no gravity feed-forward, last 3 s):\n")
  a(table(["joint", "err [rad]", "q̇ rms [rad/s]", "τ p2p [N·m]", "τ mean [N·m]", "τ sign flips / sample"], hold_rows(args.runs / "hold_g20c", args.model)))
  a("")
  a(
    "Arm 5, 6 and 7 (and mildly arm 4) fall into a limit cycle at the loop's Nyquist rate: the torque changes sign every 0.5 ms sample, "
    "saturates at the URDF's ±43 N·m and the joint velocity reads 2–22 rad/s. Most likely cause (PAL's link inertias were not inspected): discrete time, D·Δt / I well above 2 for a light wrist joint "
    "(D = 33.3, Δt = 0.5 ms), on an explicit torque law; MuJoCo's implicit integrator and the SysID armature (0.0066 kg·m²) do not show it. "
    "Sweep of the wrist damping (arm 4 at its trained D unless noted; each 6–8 s hold, `runs/hold_*`): "
    "D = 10 / 5 / 4 → arm 5 and 7 still chatter (q̇ rms 8–22 rad/s); D = 3 → still; D = 2 → stable (worst q̇ rms 0.2 rad/s); **D = 1.5 → stable (worst 0.03 rad/s)**; D = 1 → stable (0.02). "
    "Arm 1–4 hold at the trained gains once the wrists are stable.\n"
  )
  a("Stable hold with the gains that were used (arm 5–7 D = 1.5, everything else trained; `runs/hold_I`):\n")
  a(table(["joint", "err [rad]", "q̇ rms [rad/s]", "τ p2p [N·m]", "τ mean [N·m]", "τ sign flips / sample"], hold_rows(args.runs / "hold_I", args.model)))
  a("")
  a(
    "The static error is the gravity droop τ_g / K (elbow 10.9 N·m / 523.5 = 0.0208 rad; shoulder 9.1 / 998.8 = 0.0091 rad): "
    "**with G20 the arm holds 0.02 rad below its target at home, so the hand starts ~1.7 cm lower than in training.** "
    "(Arm 7's flips flag is a 0.1 N·m dither, not chatter.)\n"
  )
  a("### What was run in PAL (a deviation from the trained plant)\n")
  a(
    "* `arm_left_5/6/7` **D = 1.5** (trained 33.3), K unchanged (523.5): `GAIN_OVERRIDE` in `spawn_grasp_controller.py`, logged as `GAIN OVERRIDE …` at start.\n"
    "* `plant_lag_filter.py` low-passes the reference of arm 5–7 with τ = 0.0637 s = D / K of G20 and republishes at 250 Hz (velocity 0, effort 0). "
    "This gives the wrist the trained overdamped first-order response back. Without it the light, weakly damped wrist follows its target sooner than in training. First try (D = 1.5, no filter, T's band rebuilt from the running gains, table + stand-in): the hand was 4 cm higher than MuJoCo's at step 12 and grasped at step 186 instead of 18; with the trained band and the filter the first grasp is at step 8–20 in all nine table-only episodes (that run changed both, so the filter's share is not separated).\n"
    "* T's band uses the **trained** D / K (profile `effort_band_dk`), because the filter reproduces the trained response; the arm-1–4 controllers run the trained gains.\n"
    "* No `pal_gravity_compensation` (τ_ff = 0), `q̇_des` = 0, commands to `/subscriber_controller/desired_state` directly.\n"
  )

  a("## 4. What the deployer has to reproduce\n")
  a("```\n" + "\n".join(f"{i + 1}. {s}" for i, s in enumerate(act["pipeline"])) + "\n```\n")
  a("T's band, per arm joint (τ_cmd = 0.7 × effort; centre q + (D/K)·q̇ from the **measured** state):\n")
  a(
    table(
      ["joint", "τ_cmd [N·m]", "τ_cmd / K [rad]", "D / K [s]", "C: range [rad]"],
      [
        [
          n,
          f(v["tau_cmd_Nm"], 1),
          f(v["tau_cmd_over_K_rad"], 4),
          f(v["D_over_K_s"], 4),
          f"[{act['C_range_clip'][n][0]:.3f}, {act['C_range_clip'][n][1]:.3f}]",
        ]
        for n, v in act["T_effort_band"].items()
      ],
    )
  )
  a("\nThe jaw: clip [0, 0.78], slew 0.04 rad/step (2 rad/s, PAL's own jaw rate limit). No servo model (`LAG=none`).\n")

  a("## 5. Observations (38-D actor, in this order)\n")
  rows = []
  for t in obs["terms"]:
    n = t["name"]
    corr = obs["training_corruption"][n]
    noise = corr.get("noise", "-")
    if noise != "-":
      noise = noise.replace("NoiseModelWithAdditiveBiasCfg", "").replace("UniformNoiseCfg", "U")
      noise = noise[:110]
    rows.append([n, t["dim"], obs["definitions"][n], noise, f"{corr['delay_lag_steps'][0]}–{corr['delay_lag_steps'][1]}"])
  a(table(["term", "dim", "definition", "training noise / bias", "lag [steps]"], rows))
  a(
    "\nThe critic (not exported) has `grasped` as a 39th input; **the actor does not observe the jaw's velocity or whether the cube is held**. "
    "The cube pose is the tracker's (FoundationPose in deployment); the training gave it a per-episode bias and 0–2 steps of lag. Start observation statistics: `start_observation_distribution.json`.\n"
  )

  a("## 6. Scene the policy was trained on\n")
  a(
    table(
      ["", ""],
      [
        ["table top", f"{scene['table_top_z_env_m']} m in the env frame = {scene['table_top_z_base_link_m']:.3f} m in `base_link`; centre (0.55, 0.0), half extents {scene['table_half_xy']}"],
        ["cube", f"{scene['cube_edge_m'] * 100:.0f} cm, spawn box (env frame) x {scene['spawn_box_env']['x']}, y {scene['spawn_box_env']['y']}, every yaw (W2); centre in `base_link` {[round(v, 3) for v in scene['spawn_centre_base_link']]}"],
        ["goal", f"centre (env frame) {scene['goal_centre_env_xy']} ± {scene['goal_half_box_xy_m']} m, resting height; centre in `base_link` {[round(v, 3) for v in scene['goal_centre_base_link']]}; success threshold {scene['goal_threshold_m']} m"],
      ],
    )
  )
  a("")

  a("## 7. PAL-simulator results (2026-09-30, Geoffery)\n")
  pal = [v["pal"] for v in T["episodes"].values()]
  mj = [v["mujoco"] for v in T["episodes"].values()]
  a(
    "9 episode specs (`episodes.json`: spawn box centre, corners and edges, yaws up to ±π/4, goals ±2 cm), 6 s each, robot starting from the training pose, "
    "PAL's jaw command offset −0.0387 rad (its gripper rests 0.0387 rad off its command). The cube is virtual (PAL has no free bodies): "
    "grasp when the jaw passes the angle at which the pads meet a cube of that width across them (pad gap measured on the model, `jaw_gap` in the profile) and the cube is inside the capture envelope, "
    "carried rigidly, released when the jaw opens 0.03 rad past it.\n"
  )
  a(
    table(
      ["condition", "placed", "first grasp [s]", "first placed [s]", "cube → goal [cm]", "TCP vs MuJoCo, first 1 s, RMS [cm]"],
      [
        [
          "**PAL, table only** (T)",
          f"**{T['placed_pal']}/{T['n']}** (MuJoCo {T['placed_mujoco']}/{T['n']})",
          f"{min(x['t_first_grasp'] for x in pal):.2f}–{max(x['t_first_grasp'] for x in pal):.2f} (MuJoCo {min(x['t_first_grasp'] for x in mj):.2f}–{max(x['t_first_grasp'] for x in mj):.2f})",
          f"median {np.median([x['t_first_placed'] for x in pal]):.2f}, {min(x['t_first_placed'] for x in pal):.2f}–{max(x['t_first_placed'] for x in pal):.2f} (MuJoCo median {np.median([x['t_first_placed'] for x in mj]):.2f})",
          f"≤ {100 * max(x['final_cube_to_goal'] for x in pal):.1f}",
          f"{min(x['tcp_rms_vs_mujoco_1s_cm'] for x in pal):.1f}–{max(x['tcp_rms_vs_mujoco_1s_cm'] for x in pal):.1f} (7 of 9 ≤ 2.6)",
        ],
        ["PAL, table + static stand-in cube (TC)", f"{TC['placed_pal']}/{TC['n']}", "-", "-", "-", "-"],
      ],
    )
  )
  a("")
  a(
    "* **Open-loop replay** (MuJoCo's own commanded targets sent to PAL, table only, 9 episodes): every arm joint within 0.03 rad of MuJoCo's over the first second (max 0.010 / 0.008 / 0.016 / 0.026 / 0.014 / 0.030 / 0.013 rad on arm 1–7), RMS 0.001–0.005 rad over the episode. The jaw differs by up to 0.14–0.57 rad (PAL's gripper is a different servo with a rate limit, and holds no cube).\n"
    "* **The static stand-in is the wrong obstacle for this policy** (TC 3/9): it grasps by straddling and dragging the cube away at ~1 m/s, which a fixed box in the hand's way makes impossible once the virtual cube is held. TC is kept as a limitation, not a result; T is the test.\n"
    "* Peak TCP speed 0.80–1.14 m/s (MuJoCo 0.89–1.14); T's band moves the target on 62–67 % of steps (MuJoCo 63 %). "
    "Arm joint speed 20 ms means: 0.55–0.65 × the URDF limit on arm 1–6; **arm 7 reaches 1.84 × in one episode (7)** (MuJoCo: 0.45–0.54 × on all joints and episodes). "
    "Peak torque 20 ms means: 0.19–1.06 × T's cap; single 0.5 ms samples reach 41.7 N·m on arm 2, 32.3 on arm 4 and 22.5 on arm 3 (raw peaks are not clamped by PAL's controller).\n"
    "* The first policy inference takes ~0.5 s; without a warm-up the arm idles at the start of the first episode (fixed in the node).\n"
    "* PAL's simulator runs ≈ 0.75 × real time; everything runs on its clock.\n"
  )

  a("## 8. Still open before this goes on the robot\n")
  a(
    "1. **Wrist gains.** G20's D on arm 5–7 cannot run on PAL's explicit torque loop, and it is unknown whether it can on the robot (`impedance_control_v37` has no arm 5–7 files, and PAL's own wrist gains are p 100 / d 1). "
    "Options: run D ≈ 1.5 with a reference lag as here (needs the lag filter on the robot too), or retrain the wrists at a plant the controller can run (`G20s`-like D, or a lower wrist K with the same D/K).\n"
    "2. **Clamp effort at the training limits** (arm 1–2 35 N·m, arm 3–7 17.5 N·m as T assumes): PAL's `DirectImpedanceControl` has no such clamp, single-sample torques exceed them.\n"
    "3. **Implement T and C in the deployer** exactly as in §4 (both live in the action term; the T band uses the measured q and q̇).\n"
    "4. **Hold-and-step test on the robot** at G20's gains before any policy runs (`hold_probe.sh` is the simulator version; 0.05 rad steps per joint, watch for ringing).\n"
    "5. **Jaw**: PAL's jaw offset (−0.0387 rad here) and its 2 rad/s rate limit are simulator measurements; calibrate on the robot. The policy neither observes the jaw's velocity nor `grasped`.\n"
    "6. **Cube tracker**: the policy reads the cube pose; the sim2sim used the exact virtual cube (no noise, no lag), the training a bias ±8 mm, noise ±2 mm, 0–2 steps of lag.\n"
  )

  a("## 9. Files\n")
  a(
    "In this folder: `pick_place_profile.yaml` (node parameters), `deployment_info.yaml` (everything above, machine-readable, incl. all 30 actuators), `deployment_start_config.json`, "
    "`start_observation_distribution.json`, `params/env.yaml` + `agent.yaml` (the training run's, from IAS), `model_4999.onnx`, `mujoco_reference.npz`, `grasp_calibration.json`, `episodes.json`. "
    "Runs and logs: `../runs/` (`T2_rctp_s3`, `TC2_rctp_s3`, `RP_rctp_s3`, `hold_*`, each with `session*.yaml` = workspace commit, ONNX hash, settings). "
    "Videos: `../../../videos/sim2sim/rctp_s3/`. Code: pal_mjlab branch `siwei-sim2sim-s7` (`scripts/sim2sim/export_for_pal_s7.py`, `analyze_s7.py`, `analyze_hold_probe.py`, `compose_videos_s7.sh`, `write_deploy_notes.py`) and pal-policy-deployment branch `siwei/pick-place-sim2sim` (node, `plant_lag_filter.py`, `hold_probe.sh`, launch and session options).\n"
  )
  args.out.write_text("\n".join(L) + "\n")
  print("wrote", args.out, len("\n".join(L)), "chars")


if __name__ == "__main__":
  main()
